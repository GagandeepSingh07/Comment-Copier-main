for (const lang of SUPPORTED_LANGS) {
    const extra = EXTRA_I18N[lang];
    if (!extra) continue;
    for (const group of Object.keys(extra)) {
        Object.assign(I18N[lang][group], extra[group]);
    }
}

function getLang() {
    const v = localStorage.getItem(LANG_KEY);
    return SUPPORTED_LANGS.includes(v) ? v : 'en';
}

function t(key, vars) {
    const path = String(key).split('.');
    let val;
    outer: for (const lang of [getLang(), 'en']) {
        let node = I18N[lang];
        for (const seg of path) {
            if (!node || typeof node !== 'object' || !(seg in node)) continue outer;
            node = node[seg];
        }
        if (typeof node === 'string') { val = node; break; }
    }
    if (val === undefined) val = String(key);
    return String(val).replace(/\{(\w+)\}/g, (m, name) => (vars && name in vars) ? String(vars[name]) : m);
}

function tN(base, n, vars) {
    return t(base + (n === 1 ? '_one' : '_other'), Object.assign({ n }, vars));
}

function i18nApply(root) {
    document.documentElement.setAttribute('lang', getLang());
    document.documentElement.setAttribute('dir', getLang() === 'ar' ? 'rtl' : 'ltr');
    const r = root || document;
    r.querySelectorAll('[data-i18n]').forEach((el) => {
        const out = t(el.dataset.i18n);
        if (out !== el.dataset.i18n) el.textContent = out;
    });
    r.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const out = t(el.dataset.i18nPlaceholder);
        if (out !== el.dataset.i18nPlaceholder) el.setAttribute('placeholder', out);
    });
    r.querySelectorAll('[data-i18n-title]').forEach((el) => {
        const out = t(el.dataset.i18nTitle);
        if (out !== el.dataset.i18nTitle) el.setAttribute('title', out);
    });
    r.querySelectorAll('[data-i18n-aria]').forEach((el) => {
        const out = t(el.dataset.i18nAria);
        if (out !== el.dataset.i18nAria) el.setAttribute('aria-label', out);
    });
}